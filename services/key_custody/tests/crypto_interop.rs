//! Fixed unit-only records generated independently with libsodium 1.0.18.
//! The production Rust barrier, not a copied encoder, consumes the C ciphertext.
use keyverse_custody::{CustodyBarrier, RecordContext, RecoveryShare};
use rand_chacha::{ChaCha20Rng, rand_core::SeedableRng};
use sharks::Sharks;

#[test]
fn opens_independent_libsodium_root_and_context_bound_record() {
    let root_record = [
        0x4b, 0x56, 0x43, 0x31, 0x02, 0x03, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x30, 0x31,
        0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3a, 0x3b, 0x3c, 0x3d,
        0x3e, 0x3f, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x13, 0xba,
        0x0e, 0xd8, 0x04, 0xb2, 0x16, 0xc3, 0xe6, 0x14, 0x99, 0x56, 0x1b, 0xaa,
        0x59, 0x7a, 0x11, 0x01, 0x12, 0xd7, 0xe6, 0x90, 0x13, 0xd6, 0xb3, 0xeb,
        0x83, 0x12, 0xee, 0xe1, 0xde, 0xcb, 0xef, 0xad, 0x88, 0x37, 0xa3, 0x60,
        0xde, 0xe7, 0x47, 0xb6, 0x89, 0x48, 0xb2, 0xf8, 0x1d, 0x82,
    ];
    let protected_record = [
        0x4b, 0x56, 0x44, 0x31, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0xf5, 0xa7, 0x76, 0x09,
        0xf5, 0xa0, 0xfe, 0xcb, 0x1e, 0x2a, 0x47, 0xba, 0xa2, 0x24, 0xcd, 0xc5,
        0x28, 0x32, 0x5b, 0xd1, 0x92, 0xb2, 0x64, 0xc6, 0x14, 0x74, 0x50, 0xc1,
        0x53, 0x80, 0x94, 0x37, 0x2d, 0x71, 0xd3, 0x96, 0x07, 0xcd, 0xac, 0x04,
        0x7b, 0x18, 0xfa, 0x6f, 0x4c, 0x5e, 0x11, 0xd6, 0x42, 0x3c, 0x7d, 0x08,
    ];
    let mut dealer_random = ChaCha20Rng::from_seed([0x55; 32]);
    let share_dealer = Sharks(2);
    let recovery_shares: Vec<_> = share_dealer.dealer_rng(&[0x42; 32], &mut dealer_random)
        .take(2).map(|raw_share| {
            let mut encoded_share = b"KVS1".to_vec();
            encoded_share.extend_from_slice(&root_record[4..22]);
            encoded_share.extend_from_slice(&Vec::from(&raw_share));
            RecoveryShare::from_custodian_bytes(&encoded_share).unwrap()
        }).collect();
    let mut barrier_state = CustodyBarrier::from_sealed_record(&root_record).unwrap();
    barrier_state.unseal_custody(&recovery_shares).unwrap();
    let record_scope = RecordContext::new([
        "tenant_alpha", "production", "provider_credentials",
        "gateway_api_key", "version_1", "provider_request",
    ]).unwrap();
    assert_eq!(
        barrier_state.open_record(&record_scope, &protected_record).unwrap().expose_secret(),
        b"keyverse-native-custody-known-answer",
    );
}
